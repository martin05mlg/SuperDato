# -------------------------------------------------------------
# Registration Tokens
# -------------------------------------------------------------
@router.get("/tokens", response_model=List[RegistrationTokenResponse])
@router.get("/registration-tokens", response_model=List[RegistrationTokenResponse])
async def list_registration_tokens(
    current_admin: User = Depends(require_superuser),
    db: AsyncSession = Depends(get_db),
):
    """Lists all registration tokens generated by superadmins."""
    return await AdminService.list_registration_tokens(db)


@router.post("/tokens", response_model=RegistrationTokenResponse, status_code=status.HTTP_201_CREATED)
@router.post("/registration-tokens", response_model=RegistrationTokenResponse, status_code=status.HTTP_201_CREATED)
async def create_registration_token(
    data: RegistrationTokenCreate,
    current_admin: User = Depends(require_superuser),
    db: AsyncSession = Depends(get_db),
):
    """Generates a secure registration token required for new users to sign up."""
    return await AdminService.create_registration_token(
        db,
        creator_id=current_admin.id,
        token=data.token,
        note=data.note,
        max_uses=data.max_uses,
        expires_in_days=data.expires_in_days,
    )


@router.delete("/tokens/{token_id}")
@router.delete("/registration-tokens/{token_id}")
async def revoke_registration_token(
    token_id: uuid.UUID,
    current_admin: User = Depends(require_superuser),
    db: AsyncSession = Depends(get_db),
):
    """Revokes an active registration token."""
    return await AdminService.revoke_registration_token(db, token_id)


